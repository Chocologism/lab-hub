// Must target an isolated test server. Creates and cleans up one recommendation.
import { chromium } from '@playwright/test'
import assert from 'node:assert/strict'
const base = process.env.LABHUB_TEST_URL
if (!base) throw new Error('Set LABHUB_TEST_URL to an isolated test server')
const browser = await chromium.launch({ headless: true, channel: 'chrome' })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
const errors = []
page.on('pageerror', e => errors.push(e.message))
let headers, paperId
try {
  const login = await (await page.request.post(`${base}/api/auth/login`, { data: { email: 'student@lab.edu', password: 'lab123456' } })).json()
  headers = { Authorization: `Bearer ${login.access_token}` }
  const teacher = await (await page.request.post(`${base}/api/auth/login`, { data: { email: 'shu@lab.edu', password: 'lab123456' } })).json()
  const teacherHeaders = { Authorization: `Bearer ${teacher.access_token}` }
  const arxivId = '2609.' + String(Date.now() % 100000).padStart(5, '0')
  const paper = await page.request.post(`${base}/api/arxiv/recommend`, { headers, data: { arxiv_id: arxivId, title: `可见范围编辑测试 ${arxivId}`, authors: ['Test'], abstract: 'Test abstract', recommend_comment: '保留原推荐语' } })
  assert.equal(paper.status(), 200)
  paperId = (await paper.json()).id
  await page.goto(base)
  await page.evaluate(login => { localStorage.setItem('labhub_token', login.access_token); localStorage.setItem('labhub_user', JSON.stringify(login.user)) }, login)
  await page.goto(`${base}/arxiv`)
  await page.getByRole('button', { name: '我发出的', exact: true }).click()
  const row = page.locator('.paper-row').filter({ hasText: `可见范围编辑测试 ${arxivId}` })
  await row.getByRole('button', { name: '编辑可见范围', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '编辑可见范围', exact: true })
  await dialog.getByRole('button', { name: '定向推荐', exact: true }).click()
  assert.ok(await dialog.getByRole('button', { name: '保存可见范围' }).isDisabled())
  await dialog.getByLabel('查找接收人').fill('shu@lab.edu')
  await dialog.getByRole('checkbox').check()
  await page.screenshot({ path: '/tmp/labhub-edit-visibility.png' })
  await dialog.getByRole('button', { name: '保存可见范围' }).click()
  await dialog.waitFor({ state: 'hidden' })
  await row.locator('.badge').filter({ hasText: '定向推荐' }).waitFor()
  const received = await (await page.request.get(`${base}/api/arxiv/feed?scope=received`, { headers: teacherHeaders })).json()
  assert.ok(received.some(p => p.id === paperId))
  await row.getByRole('button', { name: '编辑可见范围', exact: true }).click()
  await dialog.getByLabel('查找接收人').fill('shu@lab.edu')
  assert.ok(await dialog.getByRole('checkbox').isChecked())
  await dialog.getByRole('checkbox').uncheck()
  await dialog.getByLabel('查找接收人').fill('wang@lab.edu')
  await dialog.getByRole('checkbox').check()
  await dialog.getByRole('button', { name: '保存可见范围' }).click()
  await dialog.waitFor({ state: 'hidden' })
  const removed = await (await page.request.get(`${base}/api/arxiv/feed?scope=received`, { headers: teacherHeaders })).json()
  assert.ok(!removed.some(p => p.id === paperId))
  const library = await (await page.request.get(`${base}/api/library?q=${arxivId}`, { headers: teacherHeaders })).json()
  assert.equal(library.length, 0)
  await page.reload()
  await page.getByRole('button', { name: '我发出的', exact: true }).click()
  await row.getByRole('button', { name: '编辑可见范围', exact: true }).click()
  await dialog.getByRole('button', { name: '公开推荐', exact: true }).click()
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  assert.ok((await row.textContent()).includes('定向推荐'))
  await row.getByRole('button', { name: '编辑可见范围', exact: true }).click()
  await dialog.getByRole('button', { name: '公开推荐', exact: true }).click()
  await dialog.getByRole('button', { name: '保存可见范围' }).click()
  await dialog.waitFor({ state: 'hidden' })
  await row.locator('.badge').filter({ hasText: '公开推荐' }).waitFor()
  assert.ok((await row.textContent()).includes('保留原推荐语'))
  await page.setViewportSize({ width: 390, height: 844 })
  await row.getByRole('button', { name: '编辑可见范围', exact: true }).click()
  await dialog.getByRole('button', { name: '定向推荐', exact: true }).click()
  await page.screenshot({ path: '/tmp/labhub-edit-visibility-mobile.png' })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  assert.deepEqual(errors, [])
  console.log('PASS: edit button, public/direct switching, recipient preselection and replacement, cancellation, persistence, access revocation, mobile dialog')
} finally {
  if (paperId) await page.request.delete(`${base}/api/arxiv/${paperId}`, { headers })
  await browser.close()
}
